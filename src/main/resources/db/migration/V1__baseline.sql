
create table accounts (
                          balance numeric(19,2) not null,
                          currency varchar(3) not null,
                          closed_at timestamp(6) with time zone,
                          created_at timestamp(6) with time zone not null,
                          id bigint generated by default as identity,
                          updated_at timestamp(6) with time zone not null,
                          user_id bigint not null,
                          version bigint not null,
                          account_number varchar(20) not null,
                          account_type varchar(20) not null check ((account_type in ('SAVINGS','CURRENT'))),
                          frozen_by_role varchar(20) check ((frozen_by_role in ('CUSTOMER','ADMIN','SUPPORT'))),
                          status varchar(20) not null check ((status in ('ACTIVE','FROZEN','CLOSED'))),
                          primary key (id),
                          constraint uk_accounts_account_number unique (account_number),
                          constraint chk_accounts_balance_non_negative check (balance >= 0)
);

create table audit_logs (
                            id bigint generated by default as identity,
                            occurred_at timestamp(6) with time zone not null,
                            user_id bigint,
                            ip_address varchar(45),
                            action varchar(50) not null,
                            entity_id varchar(50),
                            entity_type varchar(50) not null,
                            actor_email varchar(150),
                            description varchar(1000),
                            primary key (id)
);

create table beneficiaries (
                               created_at timestamp(6) with time zone not null,
                               id bigint generated by default as identity,
                               updated_at timestamp(6) with time zone not null,
                               user_id bigint not null,
                               ifsc_code varchar(11) not null,
                               account_number varchar(20) not null,
                               status varchar(20) not null check ((status in ('ACTIVE','INACTIVE'))),
                               bank_name varchar(100) not null,
                               beneficiary_name varchar(100) not null,
                               primary key (id),
                               constraint uk_beneficiaries_user_account unique (user_id, account_number)
);

create table disputes (
                          created_at timestamp(6) with time zone not null,
                          id bigint generated by default as identity,
                          raised_by_id bigint not null,
                          resolved_at timestamp(6) with time zone,
                          resolved_by_id bigint,
                          transaction_id bigint not null,
                          updated_at timestamp(6) with time zone not null,
                          version bigint not null,
                          category varchar(20) not null check ((category in ('UNAUTHORIZED','DUPLICATE','WRONG_AMOUNT','NOT_RECEIVED','OTHER'))),
                          status varchar(20) not null check ((status in ('OPEN','RESOLVED','REJECTED'))),
                          raised_by_email varchar(150) not null,
                          resolved_by_email varchar(150),
                          description varchar(500) not null,
                          resolution_note varchar(255),
                          primary key (id)
);

create table idempotency_records (
                                     created_at timestamp(6) with time zone not null,
                                     id bigint generated by default as identity,
                                     transaction_id bigint,
                                     user_id bigint not null,
                                     operation varchar(30) not null,
                                     request_hash varchar(64) not null,
                                     idempotency_key varchar(100) not null,
                                     primary key (id),
                                     constraint uk_idempotency_user_key unique (user_id, idempotency_key)
);

create table notifications (
                               created_at timestamp(6) with time zone not null,
                               id bigint generated by default as identity,
                               read_at timestamp(6) with time zone,
                               updated_at timestamp(6) with time zone not null,
                               user_id bigint not null,
                               status varchar(20) not null check ((status in ('UNREAD','READ'))),
                               type varchar(20) not null check ((type in ('TRANSACTION','ACCOUNT','SECURITY','SYSTEM','CASE_UPDATE'))),
                               title varchar(150) not null,
                               message varchar(500) not null,
                               primary key (id)
);

create table otps (
                      attempts integer not null,
                      consumed boolean not null,
                      max_attempts integer not null,
                      created_at timestamp(6) with time zone not null,
                      expires_at timestamp(6) with time zone not null,
                      id bigint generated by default as identity,
                      requested_by bigint,
                      updated_at timestamp(6) with time zone not null,
                      user_id bigint not null,
                      version bigint not null,
                      purpose varchar(30) not null check ((purpose in ('OPEN_ACCOUNT','ADD_BENEFICIARY','CASH_WITHDRAWAL','ASSISTED_TRANSFER','UPDATE_PHONE','UNFREEZE_ACCOUNT','CLOSE_ACCOUNT','CHANGE_EMAIL'))),
                      operation_hash varchar(64) not null,
                      code_hash varchar(100) not null,
                      primary key (id)
);

create table outbox_events (
                               attempts integer not null,
                               created_at timestamp(6) with time zone not null,
                               id bigint generated by default as identity,
                               published_at timestamp(6) with time zone,
                               event_id varchar(36) not null,
                               event_type varchar(40) not null,
                               event_key varchar(60) not null,
                               topic varchar(60) not null,
                               last_error varchar(500),
                               payload text not null,
                               primary key (id),
                               constraint uk_outbox_events_event_id unique (event_id)
);

create table password_setup_tokens (
                                       created_at timestamp(6) with time zone not null,
                                       expires_at timestamp(6) with time zone not null,
                                       id bigint generated by default as identity,
                                       updated_at timestamp(6) with time zone not null,
                                       used_at timestamp(6) with time zone,
                                       user_id bigint not null,
                                       purpose varchar(20) not null check ((purpose in ('ACCOUNT_SETUP','PASSWORD_RESET'))),
                                       token_hash varchar(64) not null,
                                       primary key (id),
                                       constraint uk_password_setup_tokens_hash unique (token_hash)
);

create table processed_events (
                                  id bigint generated by default as identity,
                                  processed_at timestamp(6) with time zone not null,
                                  event_id varchar(36) not null,
                                  consumer varchar(60) not null,
                                  primary key (id),
                                  constraint uk_processed_events_consumer_event unique (consumer, event_id)
);

create table refresh_tokens (
                                extended boolean not null,
                                revoked boolean not null,
                                created_at timestamp(6) with time zone not null,
                                expires_at timestamp(6) with time zone not null,
                                id bigint generated by default as identity,
                                session_expires_at timestamp(6) with time zone not null,
                                updated_at timestamp(6) with time zone not null,
                                user_id bigint not null,
                                session_id varchar(36) not null,
                                token_hash varchar(64) not null,
                                primary key (id),
                                constraint uk_refresh_tokens_hash unique (token_hash)
);

create table reversal_requests (
                                   created_at timestamp(6) with time zone not null,
                                   id bigint generated by default as identity,
                                   requested_by_id bigint not null,
                                   reversal_transaction_id bigint,
                                   reviewed_at timestamp(6) with time zone,
                                   reviewed_by_id bigint,
                                   transaction_id bigint not null,
                                   updated_at timestamp(6) with time zone not null,
                                   version bigint not null,
                                   status varchar(20) not null check ((status in ('PENDING','APPROVED','REJECTED'))),
                                   reversal_reference varchar(40),
                                   requested_by_email varchar(150) not null,
                                   reviewed_by_email varchar(150),
                                   reason varchar(255) not null,
                                   review_note varchar(255),
                                   primary key (id)
);

create table transactions (
                              amount numeric(19,2) not null,
                              currency varchar(3) not null,
                              flagged boolean default false not null,
                              from_balance_after numeric(19,2),
                              to_balance_after numeric(19,2),
                              created_at timestamp(6) with time zone not null,
                              flagged_at timestamp(6) with time zone,
                              flagged_by_id bigint,
                              from_account_id bigint,
                              id bigint generated by default as identity,
                              initiated_by_id bigint,
                              original_transaction_id bigint,
                              to_account_id bigint,
                              updated_at timestamp(6) with time zone not null,
                              status varchar(20) not null check ((status in ('PENDING','SUCCESS','FAILED','REVERSED'))),
                              type varchar(20) not null check ((type in ('DEPOSIT','WITHDRAWAL','TRANSFER','REVERSAL'))),
                              transaction_reference varchar(40) not null,
                              flagged_by_email varchar(150),
                              description varchar(255),
                              flag_reason varchar(255),
                              primary key (id),
                              constraint uk_transactions_reference unique (transaction_reference),
                              constraint chk_transactions_amount_positive check (amount > 0)
);

create table unfreeze_requests (
                                   account_id bigint not null,
                                   created_at timestamp(6) with time zone not null,
                                   id bigint generated by default as identity,
                                   requested_by_id bigint not null,
                                   reviewed_at timestamp(6) with time zone,
                                   reviewed_by_id bigint,
                                   updated_at timestamp(6) with time zone not null,
                                   version bigint not null,
                                   status varchar(20) not null check ((status in ('PENDING','APPROVED','REJECTED','CANCELLED'))),
                                   requested_by_email varchar(150) not null,
                                   reviewed_by_email varchar(150),
                                   reason varchar(255) not null,
                                   review_note varchar(255),
                                   primary key (id)
);

create table user_permissions (
                                  user_id bigint not null,
                                  permission varchar(40) not null check ((permission in ('VIEW_AUDIT_LOGS','MANAGE_USERS','FLAG_TRANSACTIONS'))),
                                  primary key (user_id, permission)
);

create table users (
                       created_at timestamp(6) with time zone not null,
                       id bigint generated by default as identity,
                       session_valid_until timestamp(6) with time zone,
                       updated_at timestamp(6) with time zone not null,
                       phone varchar(15) not null,
                       role varchar(20) not null check ((role in ('CUSTOMER','ADMIN','SUPPORT'))),
                       status varchar(20) not null check ((status in ('ACTIVE','INACTIVE','LOCKED'))),
                       active_session_id varchar(36),
                       name varchar(100) not null,
                       email varchar(150) not null,
                       password_hash varchar(255) not null,
                       primary key (id),
                       constraint uk_users_email unique (email),
                       constraint uk_users_phone unique (phone)
);

