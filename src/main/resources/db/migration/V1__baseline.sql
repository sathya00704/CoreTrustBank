    on otps (user_id, purpose);

create index idx_outbox_events_unpublished
    on outbox_events (published_at, id);

create index idx_password_setup_tokens_user
    on password_setup_tokens (user_id);

create index idx_refresh_tokens_user_id
    on refresh_tokens (user_id);

create index idx_reversal_requests_status
    on reversal_requests (status);

create index idx_reversal_requests_transaction
    on reversal_requests (transaction_id);

create index idx_transactions_from_account_created
    on transactions (from_account_id, created_at);

create index idx_transactions_to_account_created
    on transactions (to_account_id, created_at);

create index idx_transactions_status
    on transactions (status);

create index idx_unfreeze_requests_status
    on unfreeze_requests (status);

create index idx_unfreeze_requests_account
    on unfreeze_requests (account_id);

